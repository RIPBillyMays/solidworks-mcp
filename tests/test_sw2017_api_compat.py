class ApiCompatTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.scan = scan_package()

    def test_snapshot_is_present_and_looks_like_2017(self) -> None:
        bare, per_interface = load_members()
        self.assertGreater(len(bare), 5000, "sw2017_api_members.txt looks empty or truncated")
        # Two members whose absence/presence characterises 2017 (see ADR-0002).
        self.assertNotIn("SaveAs3", per_interface["IModelDocExtension"])
        self.assertIn("SaveAs", per_interface["IModelDocExtension"])
        self.assertIn("FeatureCut4", per_interface["IFeatureManager"])

    def test_scanner_finds_the_expected_volume_of_names(self) -> None:
        # Guards against the scanner silently going blind (e.g. an AST refactor
        # that makes it match nothing and so "passes").
        names = {ref.name for ref in self.scan.refs}
        self.assertGreater(len(self.scan.refs), 300)
        for expected in ("SelectByID2", "FeatureExtrusion3", "CreateLine", "GetMassProperties2",
                         "CreateSectionViewAt5", "EditRebuild3", "GetTypeName2"):
            self.assertIn(expected, names)
        self.assertGreaterEqual(len(self.scan.versioned), 6)

    def test_every_called_member_exists_in_sw2017(self) -> None:
        misses = find_misses(self.scan)
        if misses:
            print("\n" + format_misses(misses))
        self.assertEqual([], misses, format_misses(misses))

    def test_known_misses_are_fixed(self) -> None:
        # Fails while KNOWN_2017_MISSES names a member the source still calls that
        # 2017 lacks (see docs/reports/phase2-static-compat.md, section 2.6).
        misses = find_misses(self.scan, tolerate_known=False)
        self.assertEqual([], misses, format_misses(misses))

    def test_call_versioned_has_a_2017_candidate(self) -> None:
        rows = versioned_resolution(self.scan)
        unresolved = [call for call, first in rows if first is None]
        report = ["call_versioned sites (first candidate present in the 2017 typelib):"]
        for call, first in rows:
            report.append(f"  {call.where:<20} {' -> '.join(call.candidates):<62} resolves to: {first}")
        print("\n" + "\n".join(report))
        self.assertEqual(
            [],
            unresolved,
            "call_versioned sites where NO candidate exists in 2017:\n"
            + "\n".join(f"  {c.where}: {c.candidates}" for c in unresolved),
        )

    def test_allowlist_entries_are_not_real_2017_members(self) -> None:
        # An allowlisted name that IS a 2017 member is dead weight at best and,
        # at worst, would mask the day the member disappears from a snapshot.
        bare, per_interface = load_members()
        stale = []
        for entry in load_allowlist():
            if "." in entry:
                interface, _, member = entry.partition(".")
                present = member in per_interface.get(interface, ())
            else:
                present = entry in bare
            if present:
                stale.append(entry)
        self.assertEqual([], stale, f"Allowlist entries that exist in 2017 (remove them): {stale}")

    def test_allowlist_entries_have_reasons(self) -> None:
        missing = [name for name, reason in load_allowlist().items() if not reason]
        self.assertEqual([], missing, f"Allowlist entries without a '# reason': {missing}")

    def test_allowlist_entries_are_actually_used(self) -> None:
        used = {ref.name for ref in self.scan.refs}
        unused = [entry for entry in load_allowlist() if entry.split(".")[-1] not in used]
        self.assertEqual([], unused, f"Allowlist entries no source file references any more: {unused}")


class ScannerSelfTests(unittest.TestCase):
    """The scanner must flag a bad name; otherwise the real test proves nothing."""

    def _misses(self, source: str) -> set[str]:
        bare, per_interface = load_members()
        scan = scan_source(source, "fake.py")
        return {
            ref.name
            for ref in scan.refs
            if ref.how != "call_versioned" and not exists_in_2017(ref.name, ref.interfaces, bare, per_interface)
        }

    def test_flags_unknown_attribute_on_extension(self) -> None:
        source = "def f(doc):\n    ext = extension(doc)\n    ext.SaveAs9('x')\n"
        self.assertEqual({"SaveAs9"}, self._misses(source))

    def test_interface_specific_check_catches_wrong_receiver(self) -> None:
        # SaveAs3 exists in the typelib, but only on IModelDoc2, not on the extension.
        source = "def f(doc):\n    extension(doc).SaveAs3('x')\n"
        self.assertEqual({"SaveAs3"}, self._misses(source))

    def test_flags_unknown_name_in_flag_tuple(self) -> None:
        source = "_EXTENSION_METHODS = ('SelectByID2', 'BogusMember')\n"
        self.assertEqual({"BogusMember"}, self._misses(source))

    def test_flags_unknown_name_in_helper_strings(self) -> None:
        source = (
            "def f(obj):\n"
            "    flag_methods(obj, 'NopeOne')\n"
            "    value(obj, 'NopeTwo')\n"
            "    safe(obj, 'NopeThree')\n"
        )
        self.assertEqual({"NopeOne", "NopeTwo", "NopeThree"}, self._misses(source))

    def test_flags_unknown_name_iterated_into_helper(self) -> None:
        source = (
            "def f(edge):\n"
            "    for member, key in (('GetStartVertex', 'a'), ('GetNowhere', 'b')):\n"
            "        value(edge, member)\n"
        )
        self.assertEqual({"GetNowhere"}, self._misses(source))

    def test_ignores_python_library_attributes(self) -> None:
        source = "import pythoncom\n\ndef f():\n    return pythoncom.Nothing\n"
        self.assertEqual(set(), self._misses(source))

    def test_call_versioned_with_only_absent_names_is_unresolved(self) -> None:
        scan = scan_source(
            "def f(doc):\n    call_versioned(feature_manager(doc), ('FeatureCut99', ()), ('FeatureCut98', ()))\n",
            "fake.py",
        )
        bare, per_interface = load_members()
        self.assertEqual(1, len(scan.versioned))
        call = scan.versioned[0]
        self.assertFalse(any(exists_in_2017(n, call.interfaces, bare, per_interface) for n in call.candidates))


